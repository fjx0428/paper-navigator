export const PAPER_SKILL_CONTENT = `# 论文领航 · paper-reading 流程

按以下固定顺序阅读论文。除工具返回值外，不要使用任何先验论文知识；不确定的内容宁可去读原文。

## 阅读顺序

1. **fetch_arxiv**（arxiv_id）获取标题、作者、摘要并抽取章节。失败就把失败原因原样告诉用户并停止，不要编造。
2. **list_sections**（arxiv_id）看章节目录。
3. **read_section** 只读与问题、方法、数据/实验、局限相关的章节：
   - 通常 2–4 次调用，每次 max_chars ≤ 4000；
   - 全部读入模型的正文合计不超过 12000 词——这是上下文管理的硬约束，长论文靠目录挑章节解决，不靠换更大的模型；
   - References、附录默认不读。
4. **write_note** 提交完整笔记：
   - problem / method / data / limitations 各写 2–4 句中文总结，每部分至少 1 条 quotes（metrics 的每条指标必须有含该数字的原文 quote）；
   - 所有 quote 必须**逐字复制**自 fetch_arxiv 返回的摘要或 read_section 的返回文本（≥8 字符）；校验只合并空白字符；
   - 不确定的数字不要写，先回第 3 步补读。
5. write_note 被退回时：按错误清单逐条修正（补读章节或改正引用），重新提交**完整**笔记，最多重试 2 次；仍失败则如实告知用户哪条引用对不上。
6. 笔记落盘成功后，用中文向用户总结：一句话问题、方法核心、主指标、局限，并给出笔记文件路径。

## 从题目出发

用户给的是研究主题、不是 arXiv 编号时：

1. **search_arxiv** 检索，默认 5 篇、最多 8 篇。把编号和标题列出来，请用户选定。
2. 只对选定的 1–3 篇走上面的精读流程。不要一次读完检索结果。
3. 两篇以上都已经落盘、用户要求对照时，调用 **compare_notes**。对照只使用笔记里的问题、方法、数据、指标、局限。数字必须能在该笔记的 quote 里找到；笔记没写的不要用记忆补上。

## 读完之后：追问与延伸

1. 笔记落盘后的追问（「XX 为什么可行」「实验里 Y 怎么设置」）：用 **read_section** 补读对应章节后再回答，引用规则不变；笔记和已读语料里没有的，直说没有，不要靠记忆。
2. 用户要「相关工作 / 接下来读什么」：可以 read_section 读 References 章节（此时不受「默认不读 References」限制），从中挑 3 篇与用户问题最相关的，给出编号和一句话理由；不要编造参考文献。
3. 笔记的每条引用在 Markdown 里都带「（来源：§章节，第 N 页）」定位，用户想核对原文时先指路，再按需补读。

## 语言

总结与对话用中文；quotes 保持论文原文，不做翻译。
`
